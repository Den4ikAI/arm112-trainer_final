import { sql } from './tests/helpers';

/**
 * После прогона закрыть занятия, которыми помощники выдавали вызовы.
 *
 * Выдача оставляет занятие идущим — иначе курсант не начал бы вызов. Но
 * прогон делит тестовую базу с проверками сервера, и незакрытое занятие
 * привязывало бы их вызовы student1 к уже выполненному заданию (повтор —
 * 409): после e2e падало полсотни серверных тестов.
 */
export default function globalTeardown(): void {
  sql(`UPDATE lessons SET finished_at = now()
        WHERE title IN ('выдача вызова', 'выдача происшествия') AND finished_at IS NULL;`);
}
