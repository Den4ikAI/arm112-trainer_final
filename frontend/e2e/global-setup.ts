import { sql } from './tests/helpers';

/**
 * Перед прогоном — развернуть приём вызовов 112 и свернуть IP-телефон.
 *
 * С финала (обратная связь экспертов 18.10) рабочее место оператора 112
 * по умолчанию свёрнуто (`ui.op112 = 0`). Сценарии 112 написаны раньше
 * и проверяют его как есть — им 112 нужен развёрнутым. Сценарий
 * «ддс-фокус» сворачивает его сам и возвращает обратно.
 *
 * Строку заводим, если миграции ещё не прошли: их INSERT … ON CONFLICT
 * DO NOTHING значение не перепишет.
 */
export default function globalSetup(): void {
  sql(`INSERT INTO settings (key, value, title)
       VALUES ('ui.op112', '1', 'Рабочее место оператора 112')
       ON CONFLICT (key) DO UPDATE SET value = '1';`);
  // IP-телефон диспетчера ДДС (финал) по умолчанию включён и забирает
  // звонки бригаде и начальнику из их панелей. Сценарии этих панелей
  // проверяют их кнопки — телефон им не нужен. Сценарий «ip-телефон»
  // включает его сам и возвращает обратно
  sql(`INSERT INTO settings (key, value, title)
       VALUES ('ui.phone', '0', 'IP-телефон диспетчера ДДС')
       ON CONFLICT (key) DO UPDATE SET value = '0';`);
}
