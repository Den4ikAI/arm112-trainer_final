# -*- coding: utf-8 -*-
"""Закрасить адрес стенда заказчика в адресной строке эталонных кадров.

Кадры боевой системы сняты в браузере, и слева в адресной строке виден
внутренний адрес стенда заказчика. В открытый репозиторий его выносить
нельзя. Размер кадра не меняется: по нему выверены сравнения.

Запуск: python3 scrub_address.py reference/*.png
"""
import sys

from PIL import Image, ImageDraw

# Область «чипа» адреса на кадрах 1920×1080 (у кадров ДДС и карточки 112
# он стоит чуть по-разному — берём с запасом)
ОБЛАСТЬ = (140, 42, 360, 70)

for путь in sys.argv[1:]:
    im = Image.open(путь).convert("RGB")
    if im.size != (1920, 1080):
        print("пропущен, не 1920×1080:", путь)
        continue
    # Цвет подложки адресной строки — справа от чипа, там пусто
    фон = im.getpixel((420, 56))
    ImageDraw.Draw(im).rectangle(ОБЛАСТЬ, fill=фон)
    im.save(путь, optimize=True)
    print("закрашено:", путь)
