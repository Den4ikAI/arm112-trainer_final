/**
 * Элемент боевого интерфейса, которого в тренажёре нет.
 *
 * Такие кнопки оставлены нарочно: интерфейс копирует боевую ПОВ-112,
 * и убирать их — значит учить людей на непохожем экране. Но курсант,
 * нажавший на мёртвую кнопку, не должен гадать, сломалось у него
 * что-то или так и задумано.
 *
 * Поэтому они явно недоступны: курсор, подсказка и `aria-disabled`
 * для чтения с экрана. Внешний вид при этом не меняется — сравнение
 * со скриншотами боевой системы остаётся честным.
 */
export const stubProps = (what: string) => ({
  'aria-disabled': true as const,
  'data-stub': 'true',
  title: `${what} — в тренажёре не реализовано`,
  onClick: (e: React.MouseEvent) => e.preventDefault(),
});
