/**
 * Порядок служб в нижней полосе карточки — как на кадрах боевой системы:
 * номерные службы («Служба 101», «Служба 104», «Служба 102») впереди,
 * по номеру, остальные — в прежнем порядке.
 *
 * Главная служба происшествия на кадре подчёркнута. Признака «главная»
 * у нас в данных нет (столбец «Главная служба» классификатора служебный),
 * поэтому подчёркиваем первую номерную — у пожара это «Служба 101», как
 * на кадре; у происшествия без номерных служб не подчёркиваем ничего.
 */
const номер = (short: string): number | null => {
  const m = /^Служба\s+(\d+)/.exec(short);
  return m ? Number(m[1]) : null;
};

export const orderServices = (ids: string[], short: (id: string) => string) => {
  const numbered = ids
    .filter((id) => номер(short(id)) !== null)
    .sort((a, b) => (номер(short(a)) ?? 0) - (номер(short(b)) ?? 0));
  const rest = ids.filter((id) => номер(short(id)) === null);
  return { ordered: [...numbered, ...rest], main: numbered[0] ?? null };
};
