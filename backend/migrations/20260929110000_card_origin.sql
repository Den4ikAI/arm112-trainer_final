-- Откуда карточка: 'session' — заполнена курсантом-оператором 112 в учебном
-- вызове; 'teacher' — учебное происшествие для диспетчеров ДДС, созданное
-- преподавателем. Диспетчер ДДС видит только вторые (Денис, 29.09: «карточки,
-- заполненные оператором 112, не должны попадать к операторам ДДС; все
-- карточки выдаёт им только преподаватель»).
ALTER TABLE cards ADD COLUMN IF NOT EXISTS origin text NOT NULL DEFAULT 'session'
    CHECK (origin IN ('session','teacher'));
