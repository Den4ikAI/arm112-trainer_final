-- Нормативы ДДС по ответу заказчика в чате задачи (27.09.2026):
--
-- > 30 сек при поступлении карточки в систему, т.е. с момента её
-- > добавления в строку сообщений. 3 минуты на открытие карточки
-- > и добавления первой записи. Статуса и текста.
--
-- Раньше 30 секунд мы считали до первого статуса диспетчера. По ответу
-- это срок до открытия карточки, а на первую запись — три минуты.
-- Открытие фиксируется системной записью «Получена службой».
UPDATE settings
   SET title = 'Норматив открытия карточки ДДС, секунд',
       hint  = 'От поступления карточки в список до её открытия диспетчером. Ответ заказчика в чате 27.09'
 WHERE key = 'norm.ack_sec';

INSERT INTO settings (key, value, title, hint) VALUES
    ('norm.first_record_sec', '180'::jsonb,
     'Норматив первой записи ДДС, секунд',
     'От поступления карточки до первой записи диспетчера — статуса и текста. Ответ заказчика в чате 27.09')
ON CONFLICT (key) DO NOTHING;
