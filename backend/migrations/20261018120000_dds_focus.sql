-- Финал: тренажёр сосредоточен на работе диспетчера ДДС
-- (обратная связь экспертов 18.10).
--
-- 1. Рабочее место оператора 112 в интерфейсе можно свернуть. По
--    умолчанию свёрнуто: эксперты просили, чтобы 112 «глаза не мозолил».
--    Код и данные 112 остаются, администратор возвращает их в «Параметрах».
INSERT INTO settings (key, value, title, hint) VALUES
    ('ui.op112', '0', 'Рабочее место оператора 112',
     '1 — показывать приём вызовов 112 и материал для него, 0 — тренажёр только для диспетчеров ДДС')
ON CONFLICT (key) DO NOTHING;

-- 2. Самостоятельная тренировка диспетчера: учебное происшествие от
--    модели выдаётся занятием только для него одного. У занятия группы
--    этого поля нет; у личного занятия его карточки видит только он.
ALTER TABLE lessons
    ADD COLUMN solo_user_id uuid NULL REFERENCES users(id) ON DELETE CASCADE;

-- 3. Откуда взялось учебное происшествие: собрано вручную, по описанию
--    преподавателя или целиком моделью по позиции классификатора.
--    У прежних не записано.
ALTER TABLE cards
    ADD COLUMN draft_source text NULL
        CHECK (draft_source IN ('manual', 'prompt', 'ai'));
