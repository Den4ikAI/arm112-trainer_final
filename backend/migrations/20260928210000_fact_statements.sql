-- Утверждения фактов вызова для сверки описания кросс-энкодером (NLI).
--
-- Кросс-энкодер сравнивает описание курсанта с фактом и отвечает
-- «подтверждает / противоречит / молчит». Сырой ответ заявителя для
-- этого плох: «Нет, дом не газифицирован.» — модель читает «Нет,» как
-- отрицание, а легенда несёт несколько фактов в одной фразе. На наборе
-- из backend/docs/замеры/ОПИСАНИЯ.md точность на сырых ответах 67–73 %,
-- на утверждениях — 88–91 %.
--
-- Утверждение готовит модель при подготовке вызова (офлайн, в очереди),
-- преподаватель видит и правит его в разделе подготовки вызовов.
-- NULL — ещё не подготовлено: сверка тогда берёт сырой ответ и так и
-- пишет в разборе.

ALTER TABLE scenario_hidden_facts ADD COLUMN statement text;

-- Легенда — первая фраза заявителя, в ней обычно несколько сведений
-- сразу («Горит крыша частного дома, Станционная, 28»): по утверждению
-- на сведение
ALTER TABLE scenarios ADD COLUMN legend_statements text[];

-- Чем разобран текст: 'nli' — кросс-энкодер, 'llm' — генеративная модель
ALTER TABLE text_analyses ADD COLUMN engine text;

INSERT INTO settings (key, value, title, hint) VALUES
    ('analysis.engine', '0'::jsonb,
     'Чем сверять описание курсанта',
     '0 — автоматически: кросс-энкодер OpenJEV, если подключён (NLI_BASE_URL), иначе языковая модель. 1 — только кросс-энкодер. 2 — только языковая модель (на видеокарте она точнее и быстрее). Комментарии диспетчера ДДС всегда разбирает языковая модель')
ON CONFLICT (key) DO NOTHING;
