-- Активная версия классификатора.
--
-- Поле is_active было в схеме с самого начала, и запрос выбора версии
-- на него опирался, но выставлять его было некому: импорт этого не
-- делал. Работало только на запасном «бери самую свежую», из-за чего
-- повторный импорт старой версии молча подменил бы справочник,
-- по которому считается эталон.
--
-- Теперь импорт делает активной первую версию, остальные переключает
-- человек. Здесь — разовое исправление уже загруженных данных:
-- активной становится самая свежая, то есть ровно та, которой система
-- и пользовалась.
UPDATE classifier_versions
   SET is_active = true
 WHERE id = (SELECT id FROM classifier_versions ORDER BY imported_at DESC LIMIT 1)
   AND NOT EXISTS (SELECT 1 FROM classifier_versions WHERE is_active);
