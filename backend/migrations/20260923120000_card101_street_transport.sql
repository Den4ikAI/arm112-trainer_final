-- Карта 101: ветки «Улица» и «Транспорт».
--
-- ИСТОЧНИК: refs/КАРТОЧКА 112.docx, кадры image14–image39 — эксперты
-- передали их в чат задачи 21.09.2026 «для большего понимания
-- интерфейса и бизнес-процесса». Формулировки вопросов и вариантов
-- дословные, с кадров.
--
-- До этого карта 101 была снята только по ветке «Дом» (кадры
-- kartochka_02, kartochka_04): на «Улице» курсанту было нечего
-- выбирать дальше первого признака (открытый вопрос №4).
--
-- Главное, что видно на новых кадрах: карта РАСТЁТ по мере ответов.
-- На кадре 14 при пустом «Где» в ней только «Где» и «Описание»;
-- после «Улица» (кадр 15) появляются «Признак пожара (улица)»,
-- «Доступ» и «Место происшествия»; после «Открытое пламя / Дым»
-- (кадр 16) — объект горения, «Угроза людям», «Медицинская помощь»,
-- «Требуется эвакуация», «Проведена ли газификация»; после выбора
-- объекта (кадр 19) — «Правонарушение»; после «Есть правонарушение»
-- (кадр 24) — текстовое «Описание правонарушения».

-- ─── Условие показа вопроса ──────────────────────────────────────────
-- Вопрос показывается, если выполнено ХОТЯ БЫ ОДНО условие: ответ на
-- указанный вопрос содержит одно из значений (а сам тот вопрос виден).
-- NULL — вопрос показывается всегда.
--
-- Формат: [{"question": "where", "values": ["Улица"]}, ...]
--
-- Списком условий через «или», а не одним родителем: «Угроза людям» —
-- один вопрос на три ветки, и в каждой он появляется по своей причине.
-- Завести три отдельных вопроса нельзя: условие оповещения «угроза
-- людям» в классификаторе привязано к одному вопросу.
--
-- `depends_on` и `survey_options.parents` остаются как были: они
-- фильтруют варианты внутри вопроса, а `show_when` решает, показывать
-- ли вопрос целиком — в том числе текстовый, у которого вариантов нет.
ALTER TABLE survey_questions ADD COLUMN show_when jsonb;

-- ─── Порядок вопросов ────────────────────────────────────────────────
-- Одна сквозная нумерация на три ветки. Видна всегда одна ветка, поэтому
