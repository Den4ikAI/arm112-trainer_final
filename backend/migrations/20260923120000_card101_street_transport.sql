-- вопросы шли в одном порядке во всех ветках. Сверено с кадрами:
--   дом (kartochka_02): Где, Признак пожара (дом), Доступ, Дом (пламя,
--     дым), Этажность здания, Угроза людям, Внутридомовые объекты,
--     Есть ли перекрытие движения, Проведена ли газификация, Описание;
--   улица (кадры 16, 24): Где, Признак пожара (улица), Доступ, Улица
--     (пламя, дым), Место происшествия, Угроза людям, Правонарушение,
--     Медицинская помощь, Описание правонарушения, Требуется эвакуация,
--     Проведена ли газификация, Описание;
--   транспорт (кадр 35): Где, Признак пожара (транспорт), Доступ,
--     Транспорт (пламя, дым), Угроза людям, Медицинская помощь,
--     Требуется эвакуация, Описание.
UPDATE survey_questions SET sort_order = CASE id
    WHEN 'where'         THEN 1
    WHEN 'fire-sign'     THEN 2
    WHEN 'access'        THEN 5
    WHEN 'house-kind'    THEN 6
    WHEN 'storeys'       THEN 9
    WHEN 'people-threat' THEN 11
    WHEN 'inhouse'       THEN 12
    WHEN 'road-block'    THEN 17
    WHEN 'gasified'      THEN 18
    WHEN 'note'          THEN 19
  END
 WHERE type_id = '101';

