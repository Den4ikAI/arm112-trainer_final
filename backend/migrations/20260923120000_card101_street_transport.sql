-- ─── Условия оповещения получили источник ────────────────────────────
-- Три условия матрицы были привязаны к служебным ключам (`_offense`,
-- `_evacuation`, `_victims`), которые «подставляет вызывающий код».
-- Вызывающий код их так и не подставлял — условия не срабатывали
-- никогда. На кадрах карты 101 у них нашёлся настоящий источник:
-- вопросы с теми же названиями. «Есть правонарушение» на кадре 24
-- добавляет в список Службу 102 — это Классификатор МВД по условию
-- «выбран признак Правонарушение».
UPDATE condition_mapping SET question_id = 'offense', match_value = 'Есть правонарушение'
 WHERE condition = 'выбран признак Правонарушение';
UPDATE condition_mapping SET question_id = 'evacuation', match_value = 'Да'
 WHERE condition = 'треб. Эвакуация';
UPDATE condition_mapping SET question_id = 'medical-help', match_value = 'Да'
 WHERE condition = 'мед. помощь';
