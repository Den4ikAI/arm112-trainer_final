-- ─── Когда какой вопрос виден ────────────────────────────────────────
-- Ветка «Дом» видна при «Дом» — так на кадрах kartochka_02 и 14
-- (на пустом «Где» вопросов дома нет). «Здание / объект» и «Опасный
-- объект» ни на одном кадре не сняты; для них оставлено прежнее
-- поведение карты — вопросы ветки «Дом», — чтобы не отнимать у курсанта
-- то, что у него было, и не выдумывать вопросы, которых мы не видели.
UPDATE survey_questions SET show_when = '[{"question":"where","values":["Дом","Здание / объект","Опасный объект"]}]'
 WHERE type_id = '101' AND id IN ('fire-sign','house-kind','storeys','inhouse','road-block');

