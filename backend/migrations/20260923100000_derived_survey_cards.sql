-- Опросные карты, выведенные из классификатора.
--
-- Со скриншотов боевой системы сняты только три карты — 101, 104 и
-- «Взрыв». Для остальных шестнадцати типов карты не было вовсе: на
-- ДТП, «Человек в опасности», 102, 103 курсант нажимал плашку, и не
-- появлялось ничего. Классифицировать такой вызов было нечем, службы
-- не подбирались. Задача «вывести карты из классификатора» была
-- заложена с самого начала и так и не сделана.
--
-- Выведенная карта — дерево признаков группы: признак 1 → признак 2 →
-- признак 3, ровно как в столбцах классификатора. Подписи вопросов
-- тоже оттуда: «112 - Признак.1 (тип происшествия)», «112-Признак.2»,
-- «112-Признак.3». Варианты — дословные значения ячеек.
--
-- Строятся сервером при запуске и при смене активной версии
-- классификатора, поэтому здесь только новые столбцы.

-- Карта выведена из классификатора, а не снята со скриншота.
-- Выведенные пересобираются при смене версии, снятые не трогаются
ALTER TABLE survey_questions ADD COLUMN derived boolean NOT NULL DEFAULT false;

-- Вопрос зависит от ответа на другой: варианты второго признака
-- у ДТП одни, у «ДТП пострадавшие» — другие
ALTER TABLE survey_questions ADD COLUMN depends_on text;

-- При каких значениях вопроса-родителя вариант показывается.
-- NULL — показывается всегда
ALTER TABLE survey_options ADD COLUMN parents text[];
