-- Скрытый факт, который курсант уже выяснил, удалять нельзя.
--
-- Правка вызова заменяла список фактов целиком: DELETE, потом INSERT.
-- На отыгранном вызове это упиралось в ссылку из revealed_facts,
-- запрос падал, и преподаватель видел в окне переписки «internal».
-- Хуже того, реплика модели к этому моменту была уже сохранена, а
-- правка — нет: переписка показывала «изменено: hidden», хотя не
-- изменилось ничего.
--
-- Снести ссылку каскадом нельзя: revealed_facts — это история занятия,
-- из неё считается «выяснил, а не угадал». Поэтому факт, на который
-- уже ссылались, не удаляется, а снимается с учёта: в новых занятиях
-- он не предлагается и преподавателю не показывается, но прошлые
-- занятия и их разбор остаются целыми.
ALTER TABLE scenario_hidden_facts
    ADD COLUMN retired boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN scenario_hidden_facts.retired IS
    'снят с учёта правкой вызова; нужен только истории прошлых занятий';
