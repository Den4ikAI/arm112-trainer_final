-- «Сценарий реагирования» — не служба. В версии v046_11 это столбец
-- с техническими кодами сценариев («15_10», «1_2») перед «Главной
-- службой»; парсер начинал службы с него и завёл службу-призрак с
-- тысячей «оповещений». В сравнении версий она выглядела удалённой
-- службой. Парсер исправлен; здесь убираем то, что он успел записать.
DELETE FROM classifier_position_services WHERE service_id = 'scenarij-reagirovaniya';
