-- Названия служб, как их видит оператор 112 боевой системы.
--
-- Справочник служб наполняется импортом классификатора, а там служба —
-- это заголовок столбца: «Классификатор МЧС», «Классификатор СМП».
-- Для курсанта это не названия: на рабочем АРМ в окне «Добавьте службы»
-- написано «Служба 101 (ГУ МЧС России по г.Москве , …)», а в полосе
-- оповещения — «Служба 101». Учиться выбирать службу по заголовку
-- столбца — учиться не тому.
--
-- Источник: кадры `refs/СЛУЖБЫ 112/imageN.png` — окно «Добавьте службы»,
-- пролистанное целиком (материалы экспертов из чата задачи, 21.09.2026),
-- и нижняя полоса на кадрах `refs/КАРТОЧКА 112/image19, 22, 36`.
-- Сопоставлены только однозначные пары; номер кадра — в `source`.
-- Остальные службы сохраняют заголовок из классификатора, список —
-- OPEN-QUESTIONS.md, вопрос 21.
--
-- Отдельная таблица, а не только UPDATE services: на чистом развёртывании
-- миграции идут раньше импорта, и служб к этому моменту ещё нет.
-- Импорт берёт отображаемое имя отсюда (ingest/classifier.rs).

CREATE TABLE service_names (
    service_id  text PRIMARY KEY,
    -- Как в списке окна «Добавьте службы», дословно
    title       text NOT NULL,
    -- Как на плашке в полосе оповещения: часть до скобки. Так подписаны
    -- «Служба 101», «Служба 102», «Деп. ЖКХ», «Мос.Без.», «ОАТИ», «ЦОДД»
    -- на кадрах карточки
    short_title text NOT NULL,
    -- Дополнительные слова для поиска в окне добавления служб
    aliases     text[] NOT NULL DEFAULT '{}',
    source      text NOT NULL
);

