-- Соответствие вариантов опросной карты признакам классификатора.
--
-- Зачем: в карте формулировки для человека («Улица», «Дом»),
-- в классификаторе свои («на улице», «жилой дом»). Эвристикой их
-- связывать нельзя — ошибка даст неверный список служб, то есть
-- неверную оценку курсанта.
--
-- Таблица заполнена вручную по данным импортированного классификатора
-- и просмотрена глазами. Для карт, выводимых из классификатора,
-- соответствие тождественное и заполняется генератором.

CREATE TABLE sign_mapping (
    type_id      text NOT NULL,
    question_id  text NOT NULL,
    option_value text NOT NULL,
    -- Уровень признака: 1 «где», 2 «объект», 3 «признак происшествия»
    sign_level   smallint NOT NULL CHECK (sign_level BETWEEN 1 AND 3),
    sign_text    text NOT NULL,
    PRIMARY KEY (type_id, question_id, option_value, sign_text),
    FOREIGN KEY (type_id, question_id)
        REFERENCES survey_questions(type_id, id) ON DELETE CASCADE
);

-- Варианты, которые в классификации не участвуют. Держим их явно,
-- чтобы отличать «забыли сопоставить» от «сопоставлять нечему».
CREATE TABLE informational_options (
    type_id      text NOT NULL,
    question_id  text NOT NULL,
    option_value text NOT NULL,
    note         text,
    PRIMARY KEY (type_id, question_id, option_value)
);

CREATE TYPE condition_kind AS ENUM (
    'predicate',   -- зависит от ответа в карточке
    'base',        -- применяется, если ни один предикат службы не сработал
    'always'       -- подразделение службы или служебная пометка
);

CREATE TABLE condition_mapping (
    condition   text PRIMARY KEY,
    kind        condition_kind NOT NULL,
    question_id text,          -- для predicate
    match_value text           -- для predicate
);

