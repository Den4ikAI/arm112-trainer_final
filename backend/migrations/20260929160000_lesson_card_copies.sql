-- Занятие ДДС выдаёт копию учебного происшествия, а не само происшествие.
--
-- Статусы, бригада, доклады, звонки, доклад начальнику и разбор
-- привязаны к карточке. Пока занятие выдавало само происшествие, одно
-- и то же происшествие в двух занятиях или группах делило всё это:
-- работа на тренировке оказывалась уже закрытой на экзамене, а в ленте
-- появлялись две строки одной карточки (UX-проход 2, проблема A).
-- Теперь каждая выдача — своя карточка; source_card_id ведёт к исходнику
-- из «Учебного материала». Исходник удалили — копии живут.
ALTER TABLE cards
    ADD COLUMN source_card_id uuid NULL REFERENCES cards(id) ON DELETE SET NULL;

CREATE INDEX cards_source_card_idx ON cards (source_card_id) WHERE source_card_id IS NOT NULL;
