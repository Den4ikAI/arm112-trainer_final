-- Карта 101: вопросы про жилой дом — только при «Где: Дом».
--
-- «Дом (пламя, дым)» и «Внутридомовые объекты» показывались и при
-- «Здание / объект», и при «Опасный объект». Их варианты — вторые
-- признаки ветки «жилой дом» классификатора («частный дом», «квартира»,
-- «балкон»); под «объект» их нет, и ответ давал комбинацию, которой в
-- классификаторе нет. Вторые признаки «объект» (АЗС, лечебное,
-- производство…) карта теперь получает из классификатора при построении
-- (ingest/survey.rs, дополнение карт со скриншотов).
UPDATE survey_questions
   SET show_when = '[{"question":"where","values":["Дом"]}]'
 WHERE type_id = '101' AND id IN ('house-kind', 'inhouse');

-- Объект транспорта — и при сработавшей сигнализации: в классификаторе
-- есть «метро / сработала сигнализация» и «МЦК / сработала сигнализация»,
-- а до метро и МЦК можно было дойти только через «Открытое пламя / Дым».
UPDATE survey_questions
   SET show_when = '[{"question":"transport-sign","values":["Открытое пламя / Дым","Сработала пожарная сигнализация"]}]'
 WHERE type_id = '101' AND id = 'transport-object';
