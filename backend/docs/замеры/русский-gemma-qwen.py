def спросить(адрес, параметры, текст):
    тело = {"model": "local", "max_tokens": 600,
            "messages": [{"role": "user", "content": текст}], **параметры}
    t = time.time()
    req = urllib.request.Request(f"{адрес}/v1/chat/completions", data=json.dumps(тело).encode(),
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=180) as r:
        ответ = json.load(r)
    return ответ["choices"][0]["message"]["content"].strip(), time.time() - t


print("# Русский: Gemma 4 26B-A4B против Qwen3.8-27B\n")
for имя_задания, текст in ЗАДАНИЯ:
    print(f"## {имя_задания}\n\n> {текст}\n")
    for модель, (адрес, рекоменд) in МОДЕЛИ.items():
        for подпись, пар in (("рекомендованные", рекоменд), ("тренажёр, T=0,3", ТРЕНАЖЁР)):
            ответ, с = спросить(адрес, пар, текст)
            print(f"### {модель} — {подпись} ({с:.1f} с)\n\n{ответ}\n")
