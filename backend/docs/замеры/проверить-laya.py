# -*- coding: utf-8 -*-
"""Laya на нашей задаче: вопрос оператора → скрытый факт вызова.

Оператор печатает вопрос своими словами, система должна понять, про
какой из 5–8 скрытых фактов вызова он спрашивает, — или что ни про
какой, и тогда заявитель отвечает «не понял вопроса».

Задача закрытая: вариантов восемь, девятый выдумать нельзя. Это то
место, где нейроклассификатор уместен, в отличие от генерации.
"""
import importlib.util as u
import os
import sys
import time

os.environ.setdefault("HF_HOME", "/media/denis/work4/llm/hf-cache")

s = u.spec_from_file_location("набор", "/media/denis/work4/llm/набор-вопросов.py")
набор = u.module_from_spec(s); s.loader.exec_module(набор)

from laya import Router


def главное() -> int:
    print("поднимаю Laya…", flush=True)
    t0 = time.time()
    router = Router(preload=True)
    print(f"готова за {time.time() - t0:.0f} с\n", flush=True)

    верных = 0
    всего = 0
    уверенность_верных = []
    уверенность_неверных = []
    уверенность_пустых = []
    задержки = []

    for название, факты, проверки in набор.НАБОРЫ:
        print(f"══ {название} ({len(факты)} вариантов)")
        вопросы = {
            "факт": {
                "type": "choice",
                "instructions": "Про какой из этих вопросов спрашивает оператор?",
                "criteria": {ключ: текст for ключ, текст in факты.items()},
            }
        }

        for запрос, цель in проверки:
            t = time.time()
            ответ = router.predict({"body": запрос}, вопросы)
            задержки.append((time.time() - t) * 1000)

            выбор = ответ["answers"]["факт"].get("choice")
            уверен = ответ["answers"]["факт"].get("confidence", 0.0)

            всего += 1
            if цель is None:
                уверенность_пустых.append(уверен)
                знак = "·"      # правильного ответа нет, смотрим на уверенность
            elif выбор == цель:
                верных += 1
                уверенность_верных.append(уверен)
                знак = "+"
            else:
                уверенность_неверных.append(уверен)
                знак = "—"

            ожидалось = цель if цель else "(нечего отвечать)"
            print(f"  {знак} {запрос:36} → {str(выбор):10} "
                  f"{уверен:.2f}   ждали: {ожидалось}")
        print()

    сопоставимых = всего - len(уверенность_пустых)
    print(f"── итог")
    print(f"   угадано: {верных} из {сопоставимых} "
          f"({верных / сопоставимых * 100:.0f} %)")
    сред = lambda v: sum(v) / len(v) if v else 0.0
    print(f"   средняя уверенность: верных {сред(уверенность_верных):.2f}, "
          f"неверных {сред(уверенность_неверных):.2f}, "
          f"на вопросах без ответа {сред(уверенность_пустых):.2f}")
    print(f"   задержка: медиана {sorted(задержки)[len(задержки)//2]:.0f} мс, "
          f"худшая {max(задержки):.0f} мс")
    print()
    print("   отделить «не понял вопроса» можно только если уверенность на")
    print("   вопросах без ответа заметно ниже, чем на верных")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
