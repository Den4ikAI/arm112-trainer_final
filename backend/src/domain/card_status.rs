//! Статус карточки выводится из статусов реагирования служб.
//!
//! Не «переход», а вычисление: фоновая задача бежит каждые пять секунд
//! и каждый раз считает статус заново из текущего состояния. Так она
//! идемпотентна и сама себя исправляет — диспетчер, принявший карточку
//! после «Не принята», вернёт её из «Отказа» без отдельного правила.
//!
//! Правила — из BACKEND.md §6 и памятки ДДС.

/// Статусы, которые проставляет система, а не диспетчер.
/// На содержательное состояние службы они не влияют.
const SYSTEM: [&str; 2] = ["Добавлена", "Получена службой"];

/// Норматив подтверждения карточки диспетчером, секунды.
pub const ACK_NORM_SEC: i64 = 30;
/// Порог перехода в «Не завершено», часы.
pub const COMPLETION_NORM_HOURS: i64 = 48;

/// Состояние одной службы в списке оповещения.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ServiceOutcome {
    /// Последний содержательный статус. `None` — служба молчит.
    pub last: Option<String>,
}

impl ServiceOutcome {
    /// Из цепочки статусов, как они лежат в `response_entries`.
    pub fn from_chain(chain: &[String]) -> Self {
        Self {
            last: chain
                .iter()
                .rev()
                .find(|s| !SYSTEM.contains(&s.as_str()))
                .cloned(),
        }
    }

    fn is(&self, status: &str) -> bool {
        self.last.as_deref() == Some(status)
    }
}

/// Вычислить статус карточки.
///
/// Порядок проверок — это приоритет того, что важнее показать
/// в журнале. Он выведен нами, в материалах заказчика не задан;
/// записано в OPEN-QUESTIONS.md, вопрос 10.
pub fn derive(services: &[ServiceOutcome], elapsed_sec: i64) -> &'static str {
    // Оповещать некого — карточка просто зарегистрирована
    if services.is_empty() {
        return "Зарегистрирована";
    }

    if services.iter().all(|s| s.is("Работы завершены")) {
        return "Завершена";
    }

    // Отказ конкретнее, чем «застряло»: по нему видно, с кем
    // разбираться, и нужен он раньше, чем истекут 48 часов
    if services
        .iter()
        .any(|s| s.is("Отказ от выполнения работ") || s.is("Не принята"))
    {
        return "Отказ";
    }

    if elapsed_sec > COMPLETION_NORM_HOURS * 3600 {
        return "Не завершено";
    }

    // Хотя бы одна служба не подтвердила приём за норматив
    if elapsed_sec > ACK_NORM_SEC && services.iter().any(|s| s.last.is_none()) {
        return "Не оповещено";
    }

    if services.iter().any(|s| s.last.is_some()) {
        return "Отработана";
    }

    "Зарегистрирована"
}

/// Статус, выставленный человеком. Фоновая задача его не трогает:
/// иначе отметка преподавателя пропадала бы через пять секунд.
pub fn is_manual(status: &str) -> bool {
    status == "Проверена"
}

#[cfg(test)]
mod tests {
    use super::*;

    fn outcomes(items: &[&[&str]]) -> Vec<ServiceOutcome> {
        items
            .iter()
            .map(|chain| {
                ServiceOutcome::from_chain(
                    &chain.iter().map(|s| s.to_string()).collect::<Vec<_>>(),
                )
            })
            .collect()
    }

    /// Пока норматив не вышел, молчание службы — не нарушение.
    #[test]
    fn до_тридцати_секунд_молчание_не_нарушение() {
        let s = outcomes(&[&["Добавлена"], &["Добавлена"]]);
        assert_eq!(derive(&s, 29), "Зарегистрирована");
    }

    /// Требование памятки: 30 секунд на подтверждение.
    #[test]
    fn после_тридцати_секунд_молчания_карточка_не_оповещена() {
        let s = outcomes(&[&["Добавлена"], &["Добавлена"]]);
        assert_eq!(derive(&s, 31), "Не оповещено");
    }

    /// Одна служба ответила, другая молчит — карточка всё равно
    /// требует внимания.
    #[test]
    fn молчание_одной_службы_перевешивает_ответ_другой() {
        let s = outcomes(&[&["Добавлена", "Принята"], &["Добавлена"]]);
        assert_eq!(derive(&s, 60), "Не оповещено");
    }

    #[test]
    fn все_ответили_карточка_отработана() {
        let s = outcomes(&[&["Принята"], &["Принята", "Прибытие"]]);
        assert_eq!(derive(&s, 600), "Отработана");
    }

    #[test]
    fn отказ_службы_переводит_карточку_в_отказ() {
        let s = outcomes(&[&["Принята"], &["Принята", "Отказ от выполнения работ"]]);
        assert_eq!(derive(&s, 600), "Отказ");
    }

    #[test]
    fn непринятие_тоже_считается_отказом() {
        let s = outcomes(&[&["Принята"], &["Не принята"]]);
        assert_eq!(derive(&s, 600), "Отказ");
    }

    /// Диспетчер передумал и принял карточку — она сама выходит
    /// из «Отказа». Отдельного правила для этого не нужно: статус
    /// не переход, а вычисление.
    #[test]
    fn принятая_после_непринятия_карточка_выходит_из_отказа() {
        let s = outcomes(&[&["Принята"], &["Не принята", "Принята"]]);
        assert_eq!(derive(&s, 600), "Отработана");
    }

    #[test]
    fn все_завершили_карточка_завершена() {
        let s = outcomes(&[
            &["Принята", "Работы завершены"],
            &["Принята", "Прибытие", "Работы завершены"],
        ]);
        assert_eq!(derive(&s, 600), "Завершена");
    }

    /// Пока хоть одна служба не закончила, карточка не завершена.
    #[test]
    fn частичное_завершение_это_ещё_не_завершена() {
        let s = outcomes(&[&["Принята", "Работы завершены"], &["Принята", "Прибытие"]]);
        assert_eq!(derive(&s, 600), "Отработана");
    }

    #[test]
    fn через_сорок_восемь_часов_без_завершения_не_завершено() {
        let s = outcomes(&[&["Принята", "Прибытие"], &["Принята"]]);
        assert_eq!(derive(&s, 49 * 3600), "Не завершено");
    }

    /// Уже завершённую карточку 48 часов не портят.
    #[test]
    fn завершённую_карточку_время_не_меняет() {
        let s = outcomes(&[&["Принята", "Работы завершены"]]);
        assert_eq!(derive(&s, 100 * 3600), "Завершена");
    }

    /// «Добавлена» и «Получена службой» ставит система: они не считаются
    /// ответом диспетчера.
    #[test]
    fn системные_статусы_не_считаются_ответом() {
        let s = outcomes(&[&["Добавлена", "Получена службой"]]);
        assert_eq!(derive(&s, 60), "Не оповещено");
    }

    #[test]
    fn отметку_преподавателя_фоновая_задача_не_трогает() {
        assert!(is_manual("Проверена"));
        assert!(!is_manual("Отработана"));
    }
}
