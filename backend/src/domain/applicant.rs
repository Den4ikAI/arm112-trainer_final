//! Справочник статусов заявителя.
//!
//! Список неизменный — он задан инструкцией по заведению карточки,
//! раздел 5.3, — поэтому в базе его держать незачем. Но лежать он
//! должен в одном месте: значения нужны и справочнику для выпадающего
//! списка, и схеме ответа модели, и подсказке в промпте. Когда список
//! был переписан руками трижды, подсказка успела разойтись со схемой
//! и модель не предлагала «ребенок» и «участник».

pub const STATUSES: [&str; 6] =
    ["очевидец", "пострадавший", "родственник", "знакомый", "ребенок", "участник"];

/// Перечисление через запятую — для подсказки модели.
pub fn listed() -> String {
    STATUSES.join(", ")
}
