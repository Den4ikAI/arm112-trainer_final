//! Машина статусов реагирования ДДС.
//!
//! Памятка для ДДС, раздел «Проставление статусов реагирования»:
//! выбрать статус можно только последовательно. Сначала доступны два
//! первичных — «Принята» и «Не принята». После «Принята» открываются
//! статусы хода работ. После «Не принята» единственный вариант —
//! «Принята».
//!
//! Проверка обязана жить на сервере, а не только в интерфейсе: кнопку
//! можно спрятать, а запрос всё равно придёт. В режиме ДДС тренажёр
//! к тому же нарочно подсовывает курсанту неверные действия.

/// Статусы, которые проставляет система, а не диспетчер.
const SYSTEM: [&str; 2] = ["Добавлена", "Получена службой"];

/// Ход работ после «Принята», строго по порядку.
const AFTER_ACCEPTED: [&str; 5] = [
    "Начало реагирования",
    "Прибытие",
    "Проведение работ",
    "Работы завершены",
    "Отказ от выполнения работ",
];

/// Какие статусы можно выбрать следующими.
pub fn next_statuses(chain: &[String]) -> Vec<String> {
    let last = chain
        .iter()
        .rev()
        .find(|s| !SYSTEM.contains(&s.as_str()));

    let Some(last) = last else {
        return vec!["Принята".into(), "Не принята".into()];
    };

    match last.as_str() {
        "Не принята" => vec!["Принята".into()],
        // Терминальные статусы закрывают карточку для редактирования
        "Работы завершены" | "Отказ от выполнения работ" => vec![],
        "Принята" => AFTER_ACCEPTED.iter().map(|s| s.to_string()).collect(),
        other => {
            // Дальше по цепочке можно идти только вперёд
            match AFTER_ACCEPTED.iter().position(|s| *s == other) {
                Some(i) => AFTER_ACCEPTED[i + 1..].iter().map(|s| s.to_string()).collect(),
                None => vec![],
            }
        }
    }
}

/// Статусы, для которых комментарий обязателен.
/// Памятка ДДС, раздел «Полнота информации».
pub fn requires_comment(status: &str) -> bool {
    status == "Не принята" || status == "Отказ от выполнения работ"
}

/// После терминального статуса карточка закрыта для редактирования.
pub fn is_terminal(status: &str) -> bool {
    status == "Работы завершены" || status == "Отказ от выполнения работ"
}

#[cfg(test)]
mod tests {
    use super::*;

    fn chain(items: &[&str]) -> Vec<String> {
        items.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn пустая_цепочка_даёт_два_первичных_статуса() {
        assert_eq!(next_statuses(&[]), vec!["Принята", "Не принята"]);
    }

    /// «Добавлена» и «Получена службой» ставит система, диспетчер
    /// их не выбирает — на доступные варианты они не влияют.
    #[test]
    fn системные_статусы_не_считаются_действием_диспетчера() {
        assert_eq!(
            next_statuses(&chain(&["Добавлена", "Получена службой"])),
            vec!["Принята", "Не принята"]
        );
    }

    #[test]
    fn после_не_принята_остаётся_только_принять() {
        assert_eq!(next_statuses(&chain(&["Не принята"])), vec!["Принята"]);
    }

    /// Пропустить «Прибытие» и сразу закрыть работы нельзя.
    #[test]
    fn ход_работ_идёт_только_вперёд() {
        let after_arrival = next_statuses(&chain(&["Принята", "Начало реагирования", "Прибытие"]));
        assert!(!after_arrival.contains(&"Начало реагирования".to_string()));
        assert_eq!(after_arrival[0], "Проведение работ");
    }

    #[test]
    fn после_терминального_статуса_ничего_не_доступно() {
        assert!(next_statuses(&chain(&["Принята", "Работы завершены"])).is_empty());
        assert!(next_statuses(&chain(&["Принята", "Отказ от выполнения работ"])).is_empty());
    }

    #[test]
    fn отказ_и_непринятие_требуют_комментария() {
        assert!(requires_comment("Не принята"));
        assert!(requires_comment("Отказ от выполнения работ"));
        assert!(!requires_comment("Принята"));
        assert!(!requires_comment("Прибытие"));
    }
}
