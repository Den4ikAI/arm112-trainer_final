//! Свободный вопрос оператора заявителю.
//!
//! Раньше курсант выбирал вопрос из готового списка. Заказчик
//! (чат, 27.09.2026): «Диалог с заявителем исключён на этапе MVP, но вы
//! можете его сделать — это будет плюсом». Теперь курсант может спросить
//! своими словами — текстом или голосом, — а тренажёр понимает, про
//! какой из скрытых фактов вызова вопрос, и заявитель отвечает ровно
//! тем, что записано в сценарии.
//!
//! Задача закрытая: ответ — один из фактов или «ни про какой». Отсюда
//! `LabelScorer` из `ml/`, а не генерация: модель ранжирует готовые
//! варианты и не может выдумать ответ, которого нет в сценарии.
//! Замер на наших вызовах — `backend/docs/замеры/README.md`.

use crate::ml::Scored;

/// Ниже этой уверенности вопрос считается непонятым. У заглушки
/// уверенность — доля слов вопроса, совпавших со словами факта; у
/// модели — 1 для выбранного варианта и 0 для остальных.
pub const MIN_PROB: f32 = 0.34;

/// Какой вариант выбран: индекс в списке кандидатов. `None` — вопрос
/// ни про один факт: заявитель переспросит.
pub fn pick(scored: &[Scored], candidates: &[String]) -> Option<usize> {
    let best = scored
        .iter()
        .filter(|s| s.prob >= MIN_PROB)
        .max_by(|a, b| a.prob.total_cmp(&b.prob))?;
    candidates.iter().position(|c| *c == best.label)
}

/// Заявительница ли. По отчеству: «-вна», «-чна», «-кызы». По фамилии
/// не судим — «Сидорова» и «Сидоров» различимы, а «Черных» нет.
pub fn applicant_female(name: &str) -> bool {
    name.split_whitespace()
        .map(|w| w.trim_matches(|c: char| !c.is_alphabetic()).to_lowercase())
        .any(|w| w.ends_with("вна") || w.ends_with("чна") || w == "кызы")
}

/// Ответ заявителя на вопрос не по делу. Не выдумываем ответ, а
/// переспрашиваем — так же, как переспросил бы человек в панике.
pub fn not_understood(female: bool) -> &'static str {
    if female {
        "Не поняла вас, повторите, пожалуйста."
    } else {
        "Не понял вас, повторите, пожалуйста."
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn s(label: &str, prob: f32) -> Scored {
        Scored { label: label.into(), prob }
    }

    #[test]
    fn выбирается_самый_уверенный_вариант() {
        let c = vec!["Пострадавшие есть?".to_string(), "Дом газифицирован?".to_string()];
        let scored = vec![s("Дом газифицирован?", 0.9), s("Пострадавшие есть?", 0.5)];
        assert_eq!(pick(&scored, &c), Some(1));
    }

    #[test]
    fn неуверенный_ответ_значит_вопрос_не_понят() {
        let c = vec!["Пострадавшие есть?".to_string()];
        assert_eq!(pick(&[s("Пострадавшие есть?", 0.1)], &c), None);
        assert_eq!(pick(&[], &c), None);
    }

    #[test]
    fn пол_заявителя_по_отчеству() {
        assert!(applicant_female("Иванова Мария Петровна"));
        assert!(applicant_female("Кузьмина Анна Ильинична"));
        assert!(!applicant_female("Сидоров Иван Сергеевич"));
        assert!(!applicant_female("Иван"));
    }

    #[test]
    fn переспрашивает_в_своём_роде() {
        assert!(not_understood(true).starts_with("Не поняла"));
        assert!(not_understood(false).starts_with("Не понял "));
    }
}
