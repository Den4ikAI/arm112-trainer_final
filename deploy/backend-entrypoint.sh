#!/bin/sh
# Запуск сервера тренажёра в контейнере.
#
# Миграции сервер накатывает сам, а классификатор — нет: он ставится
# отдельной командой из XLSX. На чистой установке его нет, и без него
# не работают ни опросные карты, ни подбор служб. Поэтому при первом
# запуске импортируем его здесь; первая импортированная версия
# становится активной автоматически.
set -eu

echo "жду базу…"
until pg_isready -q -d "$DATABASE_URL"; do sleep 1; done

# До первого импорта таблицы может не быть вовсе — тогда psql падает,
# и это тоже означает «классификатора нет»
versions=$(psql "$DATABASE_URL" -tAc "SELECT count(*) FROM classifier_versions" 2>/dev/null || echo 0)

if [ "${versions:-0}" = "0" ]; then
  xlsx=$(ls /app/task/*.xlsx | head -n 1)
  echo "классификатора нет — импортирую ${xlsx}"
  /app/bin/import_classifier "$xlsx" "v046_24 корректировка МВД + Департамент"
else
  echo "классификатор уже загружен (версий: ${versions})"
fi

exec /app/bin/arm112
